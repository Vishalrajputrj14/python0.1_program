a = 1 # a is an integer
b = 2.0 # b is a float number
c = 3 + 4j # c is a complex number
d = True # d is a boolean
e = "Hello" # e is a string
f = [1, 2, 3] # f is a list
g = (1, 2, 3) # g is a tuple
h = {1: "one", 2: "two"} # h is a dictionary
g = None # g is a NoneType

print(a, b, c, d, e, f, g, h) # print all variables
print(type(a), type(b), type(c), type(d), type(e), type(f), type(g), type(h)) # print the types of all variables 